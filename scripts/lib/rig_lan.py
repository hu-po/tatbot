#!/usr/bin/env python3
"""`tatbot rig lan-install` — install the rig's no-uplink fallbacks on every demo-case host.

Two things, both generated by tatbot_cli.rig_lan from config/nodes.json: an ssh
config that dials a node's rig address while the tailnet is down, and one rig
clock (the node with role rig-clock serves chrony to the rig subnet; every
other host takes its time from it first). Idempotent: a file whose content is
unchanged is left alone and its service is not restarted. The rig clock's
chrony is installed with apt if missing, so the first run needs an uplink.
Stdlib only, so it runs from any node's bare clone.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts/lib"))
from tatbot_paths import bootstrap  # noqa: E402

bootstrap()
from rig_power import Remote  # noqa: E402
from tatbot_cli import EXIT_HW_UNREACHABLE, EXIT_OK, EXIT_TOOL_FAILED, nodes, rig_check, rig_lan  # noqa: E402

SYNC_WAIT_S = 30

SSH_SCRIPT = f"""set -e
umask 077
mkdir -p ~/.ssh
f={rig_lan.SSH_FILE}
cat > "$f.new"
if cmp -s "$f.new" "$f"; then rm "$f.new"; s=unchanged; else mv "$f.new" "$f"; s=written; fi
touch ~/.ssh/config
if [ "$(head -n1 ~/.ssh/config)" != "{rig_lan.SSH_INCLUDE}" ]; then
  [ -e ~/.ssh/config.bak-tatbot-rig ] || cp -p ~/.ssh/config ~/.ssh/config.bak-tatbot-rig
  {{ echo "{rig_lan.SSH_INCLUDE}"; grep -vxF "{rig_lan.SSH_INCLUDE}" ~/.ssh/config || true; }} > ~/.ssh/config.new
  mv ~/.ssh/config.new ~/.ssh/config
  s="$s, included first in ~/.ssh/config"
fi
echo "$s"
"""

# Writes stdin to $1 as root unless it already holds exactly that; prints written|unchanged.
PUT = """put() {
  new=$(cat)
  if [ "$(sudo -n cat "$1" 2>/dev/null)" = "$new" ]; then echo unchanged; return 1; fi
  sudo -n mkdir -p "$(dirname "$1")"
  printf '%s\\n' "$new" | sudo -n tee "$1" >/dev/null
  echo written
}
"""

SERVER_SCRIPT = PUT + f"""set -e
fresh=
if ! command -v chronyd >/dev/null; then
  sudo -n env DEBIAN_FRONTEND=noninteractive apt-get install -y -q -o DPkg::Lock::Timeout=120 chrony </dev/null >/dev/null \\
    || {{ echo "chrony is missing and apt-get could not install it (no uplink?)" >&2; exit 1; }}
  fresh=1
fi
grep -qs '^confdir /etc/chrony/conf.d' /etc/chrony/chrony.conf \\
  || {{ echo "/etc/chrony/chrony.conf reads no /etc/chrony/conf.d" >&2; exit 1; }}
if put {rig_lan.CHRONY_SERVER_FILE} || [ -n "$fresh" ]; then
  sudo -n systemctl enable -q chrony
  sudo -n systemctl restart chrony
fi
"""

KIND_SCRIPT = """if systemctl is-active -q chrony 2>/dev/null || systemctl is-active -q chronyd 2>/dev/null; then echo chrony
elif systemctl cat systemd-timesyncd.service >/dev/null 2>&1; then echo timesyncd
else echo none; fi"""

CHRONY_SCRIPT = PUT + f"""set -e
grep -qs '^sourcedir /etc/chrony/sources.d' /etc/chrony/chrony.conf \\
  || {{ echo "/etc/chrony/chrony.conf reads no /etc/chrony/sources.d" >&2; exit 1; }}
if put {rig_lan.CHRONY_CLIENT_FILE}; then sudo -n chronyc reload sources >/dev/null; fi
"""

TIMESYNCD_SCRIPT = PUT + f"""set -e
if put {rig_lan.TIMESYNCD_FILE}; then sudo -n systemctl restart systemd-timesyncd; fi
"""

# The source a client syncs from now: chrony's selected server, or timesyncd's.
SOURCE_SCRIPT = {
    "chrony": "chronyc -n sources 2>/dev/null | awk '$1 ~ /^\\^\\*/ {print $2}'",
    "timesyncd": "timedatectl show-timesync -p ServerAddress --value 2>/dev/null; "
                 "timedatectl show -p NTPSynchronized --value 2>/dev/null",
}


def _ok(r: subprocess.CompletedProcess, what: str) -> str:
    if r.returncode:
        raise OSError(f"{what}: {(r.stderr or r.stdout).strip()[:300] or f'exit {r.returncode}'}")
    return r.stdout.strip().splitlines()[-1] if r.stdout.strip() else ""


def _source(remote: Remote, kind: str, server: str) -> str:
    """Wait up to SYNC_WAIT_S for the client to sync from the rig clock; name what it uses."""
    deadline, seen = time.monotonic() + SYNC_WAIT_S, ""
    while True:
        lines = remote.run(SOURCE_SCRIPT[kind], timeout=15).stdout.splitlines() + ["", ""]
        seen = lines[0].strip()
        if seen == server and (kind == "chrony" or lines[1].strip() == "yes"):
            return f"synced from {server}"
        if time.monotonic() > deadline:
            return f"not yet synced from {server}" + (f" (uses {seen})" if seen else "")
        time.sleep(3)


def _install_node(name: str, remote: Remote, clock: str, server: str, ssh_text: str, subnet) -> dict:
    out = {"ssh": _ok(remote.run(SSH_SCRIPT, stdin=ssh_text), "ssh config")}
    if name == clock:
        out["clock"] = "rig clock (chrony): " + _ok(remote.run(SERVER_SCRIPT, stdin=rig_lan.chrony_server(subnet),
                                                               timeout=300), "chrony server")
        return out
    kind = _ok(remote.run(KIND_SCRIPT), "time service")
    if kind == "chrony":
        state = _ok(remote.run(CHRONY_SCRIPT, stdin=rig_lan.chrony_client(server)), "chrony source")
    elif kind == "timesyncd":
        state = _ok(remote.run(TIMESYNCD_SCRIPT, stdin=rig_lan.timesyncd_client(server)), "timesyncd")
    else:
        raise OSError("neither chrony nor systemd-timesyncd is installed")
    out["clock"] = f"{kind} from {server}: {state}; {_source(remote, kind, server)}"
    return out


def do_install(args) -> int:
    nmap = nodes.load(REPO)
    me = nodes.this_node(nmap)
    subnet = nodes.rig_subnet(REPO)
    if subnet is None:
        print("rig lan-install: config/nodes.json names no __rig__ subnet", file=sys.stderr)
        return EXIT_TOOL_FAILED
    clock = rig_lan.clock_node(nmap)
    server = nmap[clock]["lan"]
    hosts = sorted(rig_check.demo_hosts(nmap), key=lambda n: n != clock)  # the rig clock serves before its clients
    ssh_text = rig_lan.ssh_config(nmap, subnet)
    if args.plan:
        report = {"schema": "tatbot.rig-lan-plan/1", "rig_clock": clock, "server": server, "hosts": hosts,
                  "ssh_config": ssh_text, "chrony_server": rig_lan.chrony_server(subnet),
                  "chrony_client": rig_lan.chrony_client(server), "timesyncd_client": rig_lan.timesyncd_client(server)}
        if args.json:
            print(json.dumps(report, indent=2))
        else:
            print(f"rig lan-install --plan: {', '.join(hosts)}; rig clock {clock} ({server})\n")
            print(f"--- {rig_lan.SSH_FILE} on every host, `{rig_lan.SSH_INCLUDE}` first in ~/.ssh/config\n{ssh_text}")
            print(f"--- {rig_lan.CHRONY_SERVER_FILE} on {clock} (chrony installed if missing)\n"
                  f"{report['chrony_server']}")
            print(f"--- {rig_lan.CHRONY_CLIENT_FILE} on a chrony host\n{report['chrony_client']}")
            print(f"--- {rig_lan.TIMESYNCD_FILE} on a timesyncd host\n{report['timesyncd_client']}")
        return EXIT_OK
    import tatbot_runlog
    run = tatbot_runlog.init("rig-lan-install", argv=sys.argv, meta={"rig_clock": clock, "hosts": hosts})
    report = {"schema": "tatbot.rig-lan-install/1", "run_id": run.run_id, "rig_clock": clock, "nodes": {}}
    failed = unreachable = False
    for name in hosts:
        remote = Remote(name, nodes.ssh_target(nmap, name), local=name == me)
        node = report["nodes"][name] = {}
        if not remote.reachable():
            unreachable, node["error"] = True, "did not answer ssh: nothing installed there"
            run.event("node.unreachable", node=name)
            continue
        try:
            node.update(_install_node(name, remote, clock, server, ssh_text, subnet))
            run.event("node.installed", node=name, **node)
        except (OSError, subprocess.SubprocessError) as exc:
            failed, node["error"] = True, str(exc)
            run.event("node.failed", node=name, error=str(exc))
    (run.dir / "report.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    if args.json:
        print(json.dumps(report, indent=2, sort_keys=True))
    else:
        print(f"rig lan-install: rig clock {clock} ({server})")
        for name, node in report["nodes"].items():
            lines = [f"error: {node['error']}"] if "error" in node else [f"ssh: {node['ssh']}", f"clock: {node['clock']}"]
            print(f"  {name}\n" + "".join(f"    {line}\n" for line in lines), end="")
    code = EXIT_TOOL_FAILED if failed else EXIT_HW_UNREACHABLE if unreachable else EXIT_OK
    run.finalize(code)
    return code


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--json", action="store_true")
    sub = p.add_subparsers(dest="verb", required=True)
    i = sub.add_parser("install", help="install the ssh fallback and the rig clock on every demo-case host")
    i.add_argument("--plan", action="store_true", help="print the generated files and the hosts; no ssh")
    args = p.parse_args(argv)
    return do_install(args)


if __name__ == "__main__":
    sys.exit(main())
