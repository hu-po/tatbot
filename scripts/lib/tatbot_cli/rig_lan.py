"""The rig's no-uplink fallbacks, generated from config/nodes.json: ssh over rig
addresses, and one rig clock. Pure text; scripts/lib/rig_lan.py installs it.

Every `ssh` target in the fleet map is a tailnet address, and the tailnet may
not come up after a cold boot with no uplink. On the rig, ssh falls back to a
node's `lan` address when this host holds an address on the rig subnet, the
tailnet address does not answer ssh and the rig address does; `HostKeyAlias`
keeps checking the host key ssh already trusts for the tailnet address. Only a
fallback: over the tailnet a node may be served by Tailscale SSH, which admits
by tailnet identity, while its rig address admits only `authorized_keys`.

The node with role `rig-clock` (one with a battery-backed clock) serves time to
the rig subnet, falling back to its own clock with no uplink; every other rig
host takes its time from it first. Hosts without a battery boot on their last
shutdown time, so with no uplink and no rig clock their clocks disagree by the
hours the rig was off.
"""

from __future__ import annotations

import ipaddress

from tatbot_cli import nodes

SSH_FILE = "~/.ssh/tatbot-rig.conf"
SSH_INCLUDE = f"Include {SSH_FILE}"
CLOCK_ROLE = "rig-clock"
CHRONY_SERVER_FILE = "/etc/chrony/conf.d/tatbot-rig.conf"
CHRONY_CLIENT_FILE = "/etc/chrony/sources.d/tatbot-rig.sources"
TIMESYNCD_FILE = "/etc/systemd/timesyncd.conf.d/90-tatbot-rig.conf"
# A timesyncd client keeps one internet pool after the rig clock: it syncs there
# if it boots before the rig clock does, and both agree while an uplink is up.
TIMESYNCD_SECOND = "pool.ntp.org"
# Below every internet source a synced rig clock relays, above nothing.
LOCAL_STRATUM = 10
PROBE_S = 1
HEADER = "# Generated by `tatbot rig lan-install` from config/nodes.json; edits are overwritten.\n"


def _lan(rec: dict, subnet: ipaddress.IPv4Network) -> str | None:
    lan = rec.get("lan")
    try:
        return lan if lan and ipaddress.IPv4Address(lan) in subnet else None
    except ValueError:
        return None


def ssh_config(nmap: dict, subnet: ipaddress.IPv4Network) -> str:
    """One `Match` block per node with an ssh target and a rig address.

    The block matches the tailnet address, the node's name and its hostname
    alias, so it must be read before any `Host` block that sets HostName (ssh
    keeps the first value): installed as the first line of ~/.ssh/config. The
    exec runs only once the host matched, and its subnet test fails at once off
    the rig; on the rig, with the tailnet down, each probe costs up to PROBE_S."""
    blocks = [HEADER]
    for name, rec in nmap.items():
        if name.startswith("_") or not isinstance(rec, dict):
            continue
        host, lan = nodes.host_of(nmap, name), _lan(rec, subnet)
        if not host or not lan:
            continue
        names = ",".join(dict.fromkeys(n for n in (host, name, rec.get("hostname")) if n))
        answers = f"timeout {PROBE_S} bash -c '</dev/tcp/%s/22' 2>/dev/null"
        probe = f"ip -4 -o addr show to {subnet} | grep -q . && ! {answers % host} && {answers % lan}"
        blocks.append(f"\n# {name}: its rig address while this host is on the rig and the tailnet does not answer\n"
                      f'Match host {names} exec "{probe}"\n'
                      f"  HostName {lan}\n"
                      f"  HostKeyAlias {host}\n")
    return "".join(blocks)


def clock_node(nmap: dict) -> str:
    """The one node with role rig-clock; ValueError without exactly one, or without a rig address."""
    node = nodes.require_role(nmap, CLOCK_ROLE)
    if not nmap[node].get("lan"):
        raise ValueError(f"the {CLOCK_ROLE} node {node} has no `lan` address")
    return node


def chrony_server(subnet: ipaddress.IPv4Network) -> str:
    """The rig clock's chrony drop-in: its usual internet sources stay; it serves
    the rig, and with none of them reachable serves its own clock."""
    return (HEADER + f"allow {subnet}\n"
            f"local stratum {LOCAL_STRATUM}\n")


def chrony_client(server: str) -> str:
    """A chrony host's source file: the rig clock, preferred over its internet pools."""
    return HEADER + f"server {server} iburst prefer\n"


def timesyncd_client(server: str) -> str:
    """A timesyncd host's drop-in: the rig clock first, then one internet pool."""
    return HEADER + f"[Time]\nNTP={server} {TIMESYNCD_SECOND}\n"
